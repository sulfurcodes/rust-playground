fn main() {
    let num: i32 = 5; // default 32 bit integers if you dont specify type
    let age: u32 = 18; // non negative unsigned 32 bit integer
    let pi: f64 = 3.14; // 64 bit floating point number for decimals
    let grade: char = 'A'; // char data type
    let is_active: bool = true; // boolean true or false
    println!("num: {}, age: {}, pi: {}, grade: {}, is_active: {}", num, age, pi, grade, is_active);
}

